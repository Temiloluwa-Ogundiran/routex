# Path to the logo file
logo_path = "logo.png"
logo_url = r"https://res.cloudinary.com/dwcx4ksau/image/upload/v1757103183/logo_niidpc.png"

class ReceiptPDF(FPDF):
    def header(self):
        
        self.image(logo_path, x=85, w=40)
        self.ln(30)
        self.set_font("Helvetica", "B", 16)
        self.cell(0, 10, "Transaction Receipt", ln=True, align="C")
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128)
        self.cell(0, 10, "Generated by X-Aggregator", 0, 0, "C")

    def add_transaction_details(self, transaction: Transaction):
        self.set_font("Helvetica", "", 12)
        self.set_text_color(0)

        def line(label, value):
            self.set_font("Helvetica", "B", 12)
            self.cell(60, 10, f"{label}:", ln=0)
            self.set_font("Helvetica", "", 12)
            self.cell(0, 10, f"{value}", ln=1)

        line("Transaction Reference", transaction.reference)
        line("Transaction type", f"{transaction.type}")
        line("Mode", f"{transaction.mode}")
        line("Customer email", transaction.customer.email)
        line("Customer Name", transaction.details.get("customer_name", "N/A")if transaction.details else "N/A")
        line("Account Number", transaction.details.get("account_number", "N/A") if transaction.details else "N/A")
        line("Bank", transaction.details.get("bank", "N/A")if transaction.details else "N/A")
        line("Amount", f'{transaction.currency} {transaction.amount:,.2f}')
        line("Narration", transaction.narration or  "N/A")
        line("Date", transaction.created_at.strftime("%d %b %Y, %I:%M %p"))

    def add_customer_transaction_details(self, transaction: Transaction):
        self.set_font("Helvetica", "", 12)
        self.set_text_color(0)

        def line(label, value):
            self.set_font("Helvetica", "B", 12)
            self.cell(60, 10, f"{label}:", ln=0)
            self.set_font("Helvetica", "", 12)
            self.cell(0, 10, f"{value}", ln=1)

        customer_transaction_type = TransactionType.DEBIT if transaction.type == TransactionType.CREDIT else TransactionType.CREDIT
        line("Transaction Reference", transaction.reference)
        line("Mode", f"{transaction.mode}")
        line("Transaction type", f"{customer_transaction_type}")
        line("Transaction status", f"{Transaction.status}")
        line("Mode", f"{transaction.mode}")
        line('Merchant ID', transaction.merchant_id)
        line("Customer email", transaction.customer.email)
        line("Account Number", transaction.details.get("account_number", "N/A") if transaction.details else "N/A")
        line("Bank", transaction.details.get("bank", "N/A")if transaction.details else "N/A")
        line("Amount", f'{transaction.currency} {transaction.amount:,.2f}')
        line("Narration", transaction.narration if transaction.narration else f"Payment from/to {transaction.merchant.name}")
        line("Date", transaction.created_at.strftime("%d %b %Y, %I:%M %p"))

