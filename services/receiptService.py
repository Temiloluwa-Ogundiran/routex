def generate_receipt_pdf(transaction: Transaction)->str:
    """Returns output path to the generated receipt"""
    # if transaction.type != TransactionType.DEBIT:
    #     raise ValueError("Receipts can only be generated for debit transactions.")

    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".pdf")
    output_path = temp_file.name
    temp_file.close()

    pdf = ReceiptPDF()
    pdf.add_page()
    pdf.add_transaction_details(transaction)
    pdf.output(output_path)
    return output_path

def generate_receipt_pdf_bytes(transaction: Transaction) -> bytes:
    """Returns PDF as bytes (used for email attachments)."""
    pdf = ReceiptPDF()
    pdf.add_page()
    pdf.add_transaction_details(transaction)
    return bytes(pdf.output())

